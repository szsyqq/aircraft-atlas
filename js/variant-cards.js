/*
 * variant-cards.js — 具体飞行型号数据（首页「制造商→家族→具体型号」三层展示）
 *
 * 每条 = 一个在首页有独立数据卡、也能点进独立详情页的具体型号。
 * 字段：
 *   id   : 唯一 slug（用于路由 #/v/<id> 与独立照片/图库）
 *   name : 卡片标题
 *   fam  : 所属家族 id（对应 data.js 中某机型的 family 字段）
 *   era  : 代际/系列名（如 NG、Classic、neo）
 *   year : 首飞年份
 *   note : 一句话评价
 *   spec : 关键参数
 *
 * 另含：
 *   window.VARIANT_BY_ID  —— id → 条目（路由查找用）
 *   window.VARIANT_PROD   —— id → 该型号产量近似值（缺省回退家族总量）
 *   window.VARIANT_PHOTO  —— id → 该型号专属照片路径（缺省用家族图库轮换）
 */
window.VARIANT_CARDS = [];
window.VARIANT_BY_ID = {};
window.VARIANT_PROD = {};
window.VARIANT_PHOTO = {};

function VCslug(s) {
  return String(s).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").replace(/-{2,}/g, "-");
}
function VC(name, fam, era, year, note, spec) {
  var id = VCslug(name);
  var obj = { id: id, name: name, fam: fam, era: era, year: year, note: note, spec: spec };
  window.VARIANT_CARDS.push(obj);
  window.VARIANT_BY_ID[id] = obj;
}

